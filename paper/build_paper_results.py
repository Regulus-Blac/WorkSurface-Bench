"""Build the full paper results bundle in one shot (paper_spec §3).

Runs every table/figure generator, then assembles results/RESULTS.md — a
single human-readable report mapping each artifact to the claim it serves.

    python -m paper.build_paper_results [--runs runs] [--out results]

Idempotent: re-run after new model runs land to refresh everything. Missing
runs degrade gracefully (sections note "no run present").
"""

from __future__ import annotations

import argparse
import glob
import json
import os

from runner.make_tables import (build_table3, build_table4, load_runs,
                                 write_csv, write_md)
from . import appendix as ap_mod
from . import figure3 as fig_mod
from . import table5 as t5_mod
from . import tables12 as t12_mod


def _read_md(path):
    return open(path).read() if os.path.exists(path) else "_(not generated)_"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--runs", default="runs")
    ap.add_argument("--data-root", default="data/worksurface_lite")
    ap.add_argument("--out", default="results")
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)

    # Table 1 + 2
    t1 = t12_mod.build_table1()
    t2 = t12_mod.build_table2(args.data_root)
    t12_mod.write_md(t1, os.path.join(args.out, "table1_prior_comparison.md"))
    t12_mod.write_md(t2, os.path.join(args.out, "table2_dataset_stats.md"))

    # Table 3 + 4 (from runs)
    rows = load_runs(args.runs)
    have_runs = bool(rows)
    if have_runs:
        for name, tbl in (("table3_main_results", build_table3(rows)),
                          ("table4_per_surface", build_table4(rows))):
            write_csv(tbl, os.path.join(args.out, name + ".csv"))
            write_md(tbl, os.path.join(args.out, name + ".md"))

    # Table 5, Figure 3, Appendix
    t5 = t5_mod.build_table5(args.runs, args.data_root) if have_runs else None
    if t5:
        t5_mod.write_md(t5, os.path.join(args.out, "table5_failure_modes.md"))
        json.dump(t5, open(os.path.join(args.out, "table5_failure_modes.json"), "w"),
                  indent=2, ensure_ascii=False)
    fig3 = fig_mod.build_figure3(args.runs) if have_runs else None
    if fig3:
        json.dump(fig3, open(os.path.join(args.out, "figure3_data.json"), "w"),
                  indent=2, ensure_ascii=False)
        # Preserve the hand-polished publication plotter once present; it reads
        # the refreshed figure3_data.json and should not be replaced by the
        # minimal scaffold embedded in paper.figure3.
        plotter = os.path.join(args.out, "plot_figure3.py")
        if not os.path.exists(plotter):
            open(plotter, "w").write(fig_mod.PLOT_SCRIPT)
    app = ap_mod.build_appendix(args.runs, args.data_root)
    json.dump(app, open(os.path.join(args.out, "appendix.json"), "w"),
              indent=2, ensure_ascii=False)

    # ---- assemble RESULTS.md ----
    models = sorted({m for _, m in
                     ((os.path.basename(p).replace(".scored.json","").partition("_")[0],
                       os.path.basename(p).replace(".scored.json","").partition("_")[2])
                      for p in glob.glob(os.path.join(args.runs, "*.scored.json")))})
    parts = []
    parts.append("# WorkSurface-Bench — Results\n")
    parts.append("Auto-generated by `paper.build_paper_results`. Each section maps "
                 "to a claim in `docs/paper_spec_zh.md` §1/§3.\n")
    parts.append(f"**Models run:** {', '.join(models) or '(none — data-only)'}\n")

    parts.append("\n## Table 1 — Prior-benchmark comparison (C1 positioning)\n")
    parts.append(_read_md(os.path.join(args.out, "table1_prior_comparison.md")))
    parts.append("\n## Table 2 — Dataset statistics (C1 scale)\n")
    parts.append(_read_md(os.path.join(args.out, "table2_dataset_stats.md")))

    if have_runs:
        parts.append("\n## Table 3 — Main results (C4 heart)\n")
        parts.append(_read_md(os.path.join(args.out, "table3_main_results.md")))
        parts.append("\n## Table 4 — Per-surface Answer (C4 support)\n")
        parts.append(_read_md(os.path.join(args.out, "table4_per_surface.md")))
        parts.append("\n## Table 5 — Failure-mode taxonomy (C4 analysis)\n")
        parts.append(_read_md(os.path.join(args.out, "table5_failure_modes.md")))

        s = fig3["scatter_3a"]
        parts.append("\n## Figure 3 — Main finding (C4 visual evidence)\n")
        parts.append(f"- **3(a) Route–Answer scatter:** {len(s['x_route_f1'])} "
                     f"(setting×task_type) buckets, Spearman ρ = "
                     f"**{s['spearman_rho']}** (p = {s['p_value']}). "
                     f"{s['interpretation']}\n")
        g = fig3["oracle_gap_3b"]
        parts.append(f"- **3(b) Oracle gap:** Answer Oracle−Naive per model = "
                     f"{g['oracle_minus_naive']} (models {g['models']}).\n")
        c = fig3["per_surface_3c"]
        parts.append(f"- **3(c) Per-surface Answer** (mean over models): "
                     f"task types {c['task_types']}\n")
        for st, vals in c["lines"].items():
            parts.append(f"    - {st}: {vals}\n")
        parts.append("\n  Plot: `python results/plot_figure3.py` -> figure3.png\n")

    parts.append("\n## Appendix\n")
    a1 = app["A1_rubric_conversion"]
    parts.append(f"- **A1 conversion:** {a1['n_source_rubrics']} source rubrics "
                 f"over {a1['n_source_tasks']} tasks -> {a1['n_atomic_tasks']} "
                 f"atomic ({a1['atomic_per_source_task']}/source).\n")
    a2 = app["A2_surface_gates"]["summary"]
    parts.append(f"- **A2 gates:** table coverage mean "
                 f"{a2.get('table_coverage_mean'):.3f}; graph task-pass "
                 f"{a2.get('graph_task_pass_fraction')}; skills "
                 f"{a2.get('skills_retained')}/{a2.get('skills_total')}.\n")
    a5 = app["A5_contamination_probe"]
    parts.append(f"- **A5 contamination probe (S1 closed-book):** {json.dumps(a5, ensure_ascii=False)}\n")
    a11 = app["A11_route_confusion"]
    parts.append(f"- **A11 route confusion:** {json.dumps(a11, ensure_ascii=False)}\n")

    open(os.path.join(args.out, "RESULTS.md"), "w").write("\n".join(parts))
    print(f"[paper] RESULTS.md + all tables/figures -> {args.out}/")
    print(f"[paper] models: {models or '(data-only)'}")


if __name__ == "__main__":
    main()
